import pandas as pd
import numpy as np
from google.colab import files
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.neural_network import MLPClassifier
from sklearn.metrics import accuracy_score, confusion_matrix, classification_report

# Upload dataset
uploaded = files.upload()

filename = next(
    name for name in uploaded
    if name.lower().endswith(".csv")
    and "pima" in name.lower()
)

df = pd.read_csv(filename)
df.columns = df.columns.str.strip()

# Remove unnecessary index columns
df = df.loc[
    :,
    ~df.columns.str.lower().str.startswith("unnamed")
]

# Identify target column
target_candidates = [
    "outcome", "diabetes", "class", "target", "label"
]

target = next(
    (
        col for col in df.columns
        if col.strip().lower() in target_candidates
    ),
    df.columns[-1]
)

# Convert columns to numeric values
for col in df.columns:
    df[col] = pd.to_numeric(df[col], errors="coerce")

df = df.dropna(subset=[target]).reset_index(drop=True)

# Prepare features and target
X = df.drop(columns=[target])
y = df[target]

# Remove rows with invalid target labels
valid = y.isin([0, 1])
X = X.loc[valid].copy()
y = y.loc[valid].astype(int)

# Replace missing values with column medians
X = X.replace([np.inf, -np.inf], np.nan)
X = X.fillna(X.median())

# Replace impossible zero measurements with median values
zero_columns = [
    "Glucose", "BloodPressure", "SkinThickness",
    "Insulin", "BMI"
]

for col in X.columns:
    if col.lower() in [name.lower() for name in zero_columns]:
        X.loc[X[col] == 0, col] = np.nan

X = X.fillna(X.median())

print("DATASET")
print(df.head())
print("\nDataset Shape:", df.shape)
print("Input Features:", list(X.columns))
print("\nClass Distribution:")
print(y.value_counts().sort_index())

# Split dataset into training and testing sets
X_train, X_test, y_train, y_test = train_test_split(
    X, y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

# Normalize input features
scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

# Build and train ANN using backpropagation
ann = MLPClassifier(
    hidden_layer_sizes=(16, 8),
    activation="relu",
    solver="adam",
    learning_rate_init=0.001,
    max_iter=1000,
    random_state=42
)

ann.fit(X_train_scaled, y_train)

# Predict test results
y_pred = ann.predict(X_test_scaled)

# Evaluate the neural network
accuracy = accuracy_score(y_test, y_pred)

print("\n========== ANN RESULTS ==========")
print("Algorithm: Artificial Neural Network")
print("Training Method: Backpropagation")
print("Hidden Layers: 2")
print("Neurons in Hidden Layers: 16 and 8")
print("Training Samples:", len(X_train))
print("Testing Samples:", len(X_test))
print(f"Accuracy: {accuracy * 100:.2f}%")

print("\nConfusion Matrix:")
print(confusion_matrix(y_test, y_pred))

print("\nClassification Report:")
print(classification_report(
    y_test,
    y_pred,
    labels=[0, 1],
    target_names=["Non-Diabetic", "Diabetic"],
    zero_division=0
))

# Test the ANN on one new sample from the test dataset
sample = X_test.iloc[[0]]
actual = y_test.iloc[0]
predicted = ann.predict(scaler.transform(sample))[0]

print("\n========== SAMPLE TEST ==========")
print("Input Measurements:")
print(sample.to_string(index=False))
print("Actual Class:", actual)
print("Predicted Class:", predicted)

if predicted == 1:
    print("Prediction: Diabetic class")
else:
    print("Prediction: Non-Diabetic class")

print("\nExperiment 4 completed successfully!")