import pandas as pd
from google.colab import files

uploaded = files.upload()

filename = next(
    name for name in uploaded
    if name.lower().endswith(".csv")
)

df = pd.read_csv(filename)
df.columns = df.columns.str.strip()

attributes = list(df.columns[:-1])
target = df.columns[-1]
n = len(attributes)

BOTTOM = "Ø"
ANY = "?"

domains = [
    df[attr].dropna().astype(str).unique().tolist()
    for attr in attributes
]

S = [(BOTTOM,) * n]
G = [(ANY,) * n]


def covers(h, x):
    return all(
        h[i] == ANY or h[i] == x[i]
        for i in range(n)
    )


def more_general_or_equal(h1, h2):
    return all(
        h1[i] == ANY or h1[i] == h2[i]
        for i in range(n)
    )


def minimal_generalizations(h, x):
    result = list(h)

    for i in range(n):
        if result[i] == BOTTOM:
            result[i] = x[i]
        elif result[i] != x[i]:
            result[i] = ANY

    return [tuple(result)]


def minimal_specializations(h, x):
    results = []

    for i in range(n):
        if h[i] == ANY:
            for value in domains[i]:
                if value != x[i]:
                    new_h = list(h)
                    new_h[i] = value
                    results.append(tuple(new_h))

    return results


def prune_S(boundary):
    boundary = list(dict.fromkeys(boundary))

    return [
        h for h in boundary
        if not any(
            h != other and more_general_or_equal(h, other)
            for other in boundary
        )
    ]


def prune_G(boundary):
    boundary = list(dict.fromkeys(boundary))

    return [
        h for h in boundary
        if not any(
            h != other and more_general_or_equal(other, h)
            for other in boundary
        )
    ]


print("Training Dataset:")
print(df)

for index, row in df.iterrows():
    x = tuple(str(row[a]) for a in attributes)
    label = str(row[target]).strip().lower()

    if label in ["yes", "positive", "1", "1.0", "true"]:
        G = [g for g in G if covers(g, x)]

        new_S = []

        for s in S:
            if covers(s, x):
                new_S.append(s)
            else:
                new_S.extend(minimal_generalizations(s, x))

        S = prune_S([
            h for h in new_S
            if any(
                more_general_or_equal(g, h)
                for g in G
            )
        ])

    elif label in ["no", "negative", "0", "0.0", "false"]:
        S = [s for s in S if not covers(s, x)]

        new_G = []

        for g in G:
            if not covers(g, x):
                new_G.append(g)
            else:
                for h in minimal_specializations(g, x):
                    if any(
                        more_general_or_equal(h, s)
                        for s in S
                    ):
                        new_G.append(h)

        G = prune_G([
            h for h in new_G
            if any(
                more_general_or_equal(h, s)
                for s in S
            )
        ])

    else:
        raise ValueError(
            f"Unknown class label '{row[target]}' "
            f"in training example {index + 1}"
        )

    print(f"\nAfter Training Example {index + 1}:")
    print("S Boundary:", S)
    print("G Boundary:", G)

print("\n========== FINAL RESULT ==========")

print("\nFinal Specific Boundary (S):")
for h in S:
    print(h)

print("\nFinal General Boundary (G):")
for h in G:
    print(h)