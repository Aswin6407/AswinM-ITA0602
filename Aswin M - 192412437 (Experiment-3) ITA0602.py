# Calculate entropy
def entropy(data):
    counts = data[target].value_counts()
    total = len(data)
    result = 0

    for count in counts:
        probability = count / total
        result -= probability * math.log2(probability)

    return result


# Calculate information gain
def information_gain(data, attribute):
    total_entropy = entropy(data)
    weighted_entropy = 0

    for value in data[attribute].unique():
        subset = data[data[attribute] == value]
        weighted_entropy += (
            len(subset) / len(data)
        ) * entropy(subset)

    return total_entropy - weighted_entropy


# Build the ID3 decision tree
def id3(data, attributes):
    labels = data[target]

    # All samples belong to one class
    if labels.nunique() == 1:
        return labels.iloc[0]

    # No attributes remain
    if not attributes:
        return labels.mode()[0]

    # Select attribute with maximum information gain
    gains = {
        attribute: information_gain(data, attribute)
        for attribute in attributes
    }

    best_attribute = max(gains, key=gains.get)

    tree = {best_attribute: {}}
    remaining_attributes = [
        attribute for attribute in attributes
        if attribute != best_attribute
    ]

    for value in data[best_attribute].unique():
        subset = data[data[best_attribute] == value]

        if subset.empty:
            tree[best_attribute][value] = labels.mode()[0]
        else:
            tree[best_attribute][value] = id3(
                subset, remaining_attributes
            )

    return tree


# Display the decision tree
tree = id3(df, attributes)

print("\nINFORMATION GAIN")
